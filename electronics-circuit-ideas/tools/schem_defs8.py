def rf_sniffer():      # Fig 27.33, netlist rf-sniffer-fig27.33
    s = Sch()
    P, N, O = opamp_at(s, (17, 4.2)); y = N[1]
    s.VS((0, y), (0, y-3.2), 'Vcoil\n（拾音線圈）', 'left'); s.gnd((0, y-3.2))
    s.R((0, y), (3.4, y), 'Rcoil\n100', 'up'); s.W((3.4, y), (4.6, y)); s.dot((4.6, y))
    s.C((4.6, y), (4.6, y-3.2), 'C2\n0.01µ', 'right'); s.gnd((4.6, y-3.2))
    s.C((4.6, y), (8.4, y), 'C1\n4.7µ', 'up'); s.R((8.4, y), (12.2, y), 'R1\n1k', 'up'); s.W((12.2, y), (13.4, y)); s.dot((13.4, y))
    s.C((13.4, y), (13.4, y-3.2), 'C5\n0.01µ', 'right') if False else None
    s.W((13.4, y), N)
    s.dot((13.4, y)); s.W((13.4, y), (13.4, y+2.4), (O[0]+1.4, y+2.4)); s.R((13.4, y+2.4), (O[0]+1.4, y+2.4), 'R5\n100k', 'up')
